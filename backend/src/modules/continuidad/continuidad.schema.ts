import { z } from 'zod';
import { idSchema } from '../../shared/admin/admin.schema.js';
export const paginaSchema=z.object({pagina:z.coerce.number().int().min(1).max(100000).default(1),limite:z.coerce.number().int().min(1).max(50).default(10)}).strict();
const motivo=z.string().trim().min(1).max(1000);
export const relevarSchema=z.object({archivo_id:idSchema,asignacion_saliente_id:idSchema,responsable_entrante_id:idSchema,motivo,confirmar:z.literal(true)}).strict();
export const confirmarSchema=z.object({confirmar:z.literal(true)}).strict();
export const aceptarOriginalSchema=z.object({documento_id:idSchema,motivo,confirmar_tenencia:z.literal(true),continuar_ubicacion:z.boolean(),archivador_id:idSchema.nullable()}).strict();
export const designarSchema=z.object({movimiento_id:idSchema,intervencion:z.enum(['ORIGEN','DESTINO']),sustituto_id:idSchema,relevo_id:idSchema.optional(),motivo,confirmar_autorizacion:z.literal(true)}).strict();
export const finalizarSchema=z.object({motivo,confirmar:z.literal(true)}).strict();
export const ejecutarSchema=z.object({operacion:z.enum(['RECIBIR','RECHAZAR','RECUPERAR','CANCELAR']),motivo,confirmar_hecho:z.literal(true),archivador_id:idSchema.nullable()}).strict();
export type Pagina=z.infer<typeof paginaSchema>;
export type Relevar=z.infer<typeof relevarSchema>;
export type Aceptar=z.infer<typeof aceptarOriginalSchema>;
export type Designar=z.infer<typeof designarSchema>;
export type Ejecutar=z.infer<typeof ejecutarSchema>;
