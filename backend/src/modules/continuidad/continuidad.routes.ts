import {Router} from 'express';
import {requiereAuth} from '../../middlewares/auth.middleware.js';
import * as c from './continuidad.controller.js';
export const continuidadRouter=Router();
continuidadRouter.use(requiereAuth);
continuidadRouter.use((_q,r,next)=>{r.setHeader('Cache-Control','no-store, private');next();});
continuidadRouter.get('/relevos',c.listar);
continuidadRouter.post('/relevos',c.formalizar);
continuidadRouter.get('/relevos/:id/originales',c.pendientes);
continuidadRouter.post('/relevos/:id/aceptacion',c.aceptar);
continuidadRouter.post('/relevos/:id/originales',c.original);
continuidadRouter.get('/sustituciones',c.sustituciones);
continuidadRouter.post('/sustituciones',c.designar);
continuidadRouter.post('/sustituciones/:id/finalizacion',c.finalizar);
continuidadRouter.post('/sustituciones/:id/actuacion',c.ejecutar);
